CREATE TABLE operator (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  msisdn_prefixes VARCHAR(200) NOT NULL,
  jasmin_connector VARCHAR(80) NOT NULL,
  dlr_billing_rule VARCHAR(20) NOT NULL DEFAULT 'ON_DELIVERED',
  max_tps INT NOT NULL DEFAULT 50,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE short_code (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number VARCHAR(20) NOT NULL,
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  valid_from TIMESTAMP WITH TIME ZONE,
  valid_to TIMESTAMP WITH TIME ZONE,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  CONSTRAINT uq_shortcode UNIQUE (number, operator_id)
);
CREATE TABLE partner (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  share_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
  webhook_url VARCHAR(400),
  webhook_secret VARCHAR(120)
);
CREATE TABLE vas_service (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  type VARCHAR(20) NOT NULL,
  partner_id BIGINT REFERENCES partner(id),
  short_code_id BIGINT NOT NULL REFERENCES short_code(id),
  status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  regulated BOOLEAN NOT NULL DEFAULT FALSE,
  regulatory_approved BOOLEAN NOT NULL DEFAULT FALSE,
  consent_mode VARCHAR(20) NOT NULL DEFAULT 'SIMPLE_OPT_IN',
  opens_at TIMESTAMP WITH TIME ZONE,
  closes_at TIMESTAMP WITH TIME ZONE,
  max_actions_per_msisdn INT NOT NULL DEFAULT 0,
  reply_ok VARCHAR(500),
  reply_stop VARCHAR(500),
  reply_help VARCHAR(500),
  reply_limit VARCHAR(500),
  reply_closed VARCHAR(500)
);
CREATE TABLE keyword (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES vas_service(id),
  word VARCHAR(40) NOT NULL,
  CONSTRAINT uq_keyword UNIQUE (service_id, word)
);
CREATE TABLE tariff (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES vas_service(id),
  event_type VARCHAR(20) NOT NULL,
  gross_amount DECIMAL(12,3) NOT NULL,
  operator_percent DECIMAL(5,2) NOT NULL,
  tax_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
  effective_from TIMESTAMP WITH TIME ZONE NOT NULL,
  approved BOOLEAN NOT NULL DEFAULT FALSE,
  created_by VARCHAR(80) NOT NULL
);
CREATE TABLE mo_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  dedup_key VARCHAR(120) NOT NULL,
  operator_msg_id VARCHAR(80),
  msisdn VARCHAR(20) NOT NULL,
  short_code VARCHAR(20) NOT NULL,
  content VARCHAR(1000) NOT NULL,
  received_at TIMESTAMP WITH TIME ZONE NOT NULL,
  service_id BIGINT REFERENCES vas_service(id),
  outcome VARCHAR(30) NOT NULL,
  CONSTRAINT uq_mo_dedup UNIQUE (operator_id, dedup_key)
);
CREATE TABLE mt_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correlation_id VARCHAR(60) NOT NULL UNIQUE,
  client_ref VARCHAR(80),
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  service_id BIGINT REFERENCES vas_service(id),
  msisdn VARCHAR(20) NOT NULL,
  sender VARCHAR(20) NOT NULL,
  content VARCHAR(1000) NOT NULL,
  encoding VARCHAR(10) NOT NULL,
  segments INT NOT NULL,
  priority VARCHAR(15) NOT NULL,
  status VARCHAR(20) NOT NULL,
  raw_status VARCHAR(40),
  smsc_message_id VARCHAR(80),
  attempts INT NOT NULL DEFAULT 0,
  billable BOOLEAN NOT NULL DEFAULT FALSE,
  mo_id BIGINT,
  api_client_id BIGINT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  validity_until TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_mt_smsc ON mt_message(smsc_message_id);
CREATE TABLE mt_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mt_id BIGINT NOT NULL REFERENCES mt_message(id),
  status VARCHAR(20) NOT NULL,
  raw_status VARCHAR(40),
  at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE subscription (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  msisdn VARCHAR(20) NOT NULL,
  service_id BIGINT NOT NULL REFERENCES vas_service(id),
  status VARCHAR(20) NOT NULL,
  activated_at TIMESTAMP WITH TIME ZONE,
  next_renewal_at TIMESTAMP WITH TIME ZONE,
  stopped_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT uq_sub UNIQUE (msisdn, service_id)
);
CREATE TABLE consent_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  msisdn VARCHAR(20) NOT NULL,
  service_id BIGINT NOT NULL REFERENCES vas_service(id),
  action VARCHAR(20) NOT NULL,
  channel VARCHAR(20) NOT NULL,
  proof_text VARCHAR(1000),
  terms_version VARCHAR(20),
  at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ledger_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(100) NOT NULL UNIQUE,
  event_type VARCHAR(20) NOT NULL,
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  service_id BIGINT REFERENCES vas_service(id),
  short_code VARCHAR(20),
  msisdn VARCHAR(20) NOT NULL,
  gross_amount DECIMAL(12,3) NOT NULL,
  operator_share DECIMAL(12,3) NOT NULL,
  provider_share DECIMAL(12,3) NOT NULL,
  partner_share DECIMAL(12,3) NOT NULL,
  taxes DECIMAL(12,3) NOT NULL,
  billing_status VARCHAR(20) NOT NULL,
  source_reference VARCHAR(100),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE recon_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id VARCHAR(40) NOT NULL,
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  event_id VARCHAR(100),
  operator_amount DECIMAL(12,3),
  platform_amount DECIMAL(12,3),
  result VARCHAR(30) NOT NULL,
  comment VARCHAR(400)
);
CREATE TABLE api_client (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  key_hash VARCHAR(64) NOT NULL UNIQUE,
  scopes VARCHAR(200) NOT NULL,
  partner_id BIGINT REFERENCES partner(id),
  rate_limit_per_min INT NOT NULL DEFAULT 600,
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor VARCHAR(80) NOT NULL,
  action VARCHAR(60) NOT NULL,
  target VARCHAR(120),
  detail VARCHAR(1000),
  at TIMESTAMP WITH TIME ZONE NOT NULL
);
