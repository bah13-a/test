-- Options intégrées : canaux USSD, IVR, WhatsApp / RCS, paiement sur facture opérateur (DCB) et antifraude.
-- Canal d'origine des MO et canal d'envoi des MT (SMS par défaut : comportement inchangé pour l'existant).
ALTER TABLE mo_message ADD COLUMN channel VARCHAR(12) DEFAULT 'SMS' NOT NULL;
ALTER TABLE mt_message ADD COLUMN channel VARCHAR(12) DEFAULT 'SMS' NOT NULL;
CREATE INDEX ix_mo_msisdn_received ON mo_message (msisdn, received_at);

-- Antifraude : alertes (à acquitter) et blocages temporaires de numéros.
CREATE TABLE fraud_alert (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rule VARCHAR(40) NOT NULL,
  msisdn VARCHAR(100),
  service_id BIGINT REFERENCES vas_service(id),
  detail VARCHAR(500) NOT NULL,
  status VARCHAR(12) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  acknowledged_by VARCHAR(80),
  acknowledged_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_fraud_alert_status ON fraud_alert (status, created_at);
CREATE TABLE fraud_block (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  msisdn VARCHAR(100) NOT NULL,
  rule VARCHAR(40) NOT NULL,
  reason VARCHAR(300) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  until_at TIMESTAMP WITH TIME ZONE NOT NULL,
  lifted_by VARCHAR(80)
);
CREATE INDEX ix_fraud_block_msisdn ON fraud_block (msisdn, until_at);

-- Menus interactifs USSD et IVR : arbre JSON (texte, options par touche, actions) rattaché à un service.
CREATE TABLE menu_definition (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel VARCHAR(12) NOT NULL,
  code VARCHAR(40) NOT NULL,
  service_id BIGINT NOT NULL REFERENCES vas_service(id),
  definition TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_by VARCHAR(80),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_menu_channel_code UNIQUE (channel, code)
);
CREATE TABLE ussd_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id VARCHAR(100) NOT NULL UNIQUE,
  msisdn VARCHAR(100) NOT NULL,
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  menu_id BIGINT NOT NULL REFERENCES menu_definition(id),
  path VARCHAR(200) NOT NULL,
  status VARCHAR(12) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ivr_call (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  call_id VARCHAR(100) NOT NULL UNIQUE,
  msisdn VARCHAR(100) NOT NULL,
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  menu_id BIGINT NOT NULL REFERENCES menu_definition(id),
  path VARCHAR(200) NOT NULL,
  status VARCHAR(12) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  ended_at TIMESTAMP WITH TIME ZONE,
  duration_seconds INT NOT NULL DEFAULT 0
);

-- Paiement sur facture opérateur (DCB) : une transaction par demande de paiement, confirmée par code à usage unique.
CREATE TABLE dcb_transaction (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tx_id VARCHAR(60) NOT NULL UNIQUE,
  api_client_id BIGINT NOT NULL REFERENCES api_client(id),
  service_id BIGINT NOT NULL REFERENCES vas_service(id),
  operator_id BIGINT NOT NULL REFERENCES operator(id),
  msisdn VARCHAR(100) NOT NULL,
  amount DECIMAL(12,3) NOT NULL,
  description VARCHAR(200),
  status VARCHAR(20) NOT NULL,
  otp_hash VARCHAR(100),
  otp_expires_at TIMESTAMP WITH TIME ZONE,
  otp_attempts INT NOT NULL DEFAULT 0,
  client_ref VARCHAR(80),
  provider_ref VARCHAR(100),
  error VARCHAR(300),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_dcb_client_ref UNIQUE (api_client_id, client_ref)
);

-- Messagerie enrichie : un compte WhatsApp / agent RCS est rattaché à un short code (ses mots-clés et services s'appliquent).
CREATE TABLE chat_channel (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR(12) NOT NULL,
  address VARCHAR(100) NOT NULL,
  short_code_id BIGINT NOT NULL REFERENCES short_code(id),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_chat_channel UNIQUE (kind, address)
);
