-- Entrepôt de données (schéma en étoile) alimenté par l'ETL nocturne (tn.vas.dwh.EtlJob). Grain : le jour (colonne fact_day).
-- Dimensions : dw_service (service, type, partenaire, short code, opérateur) ; les jours sont des colonnes DATE (dimension implicite).
-- Faits : facturation (dw_fact_billing), trafic (dw_fact_traffic), mouvements d'abonnés (dw_fact_subscription). service_id 0 = aucun service.
CREATE TABLE dw_service (
  service_id BIGINT PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  type VARCHAR(30) NOT NULL,
  partner_name VARCHAR(200),
  short_code VARCHAR(20),
  operator_code VARCHAR(20),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE dw_fact_billing (
  fact_day DATE NOT NULL,
  service_id BIGINT NOT NULL,
  operator_id BIGINT NOT NULL,
  event_type VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL,
  events BIGINT NOT NULL,
  gross DECIMAL(16,3) NOT NULL,
  operator_share DECIMAL(16,3) NOT NULL,
  partner_share DECIMAL(16,3) NOT NULL,
  provider_share DECIMAL(16,3) NOT NULL,
  taxes DECIMAL(16,3) NOT NULL,
  PRIMARY KEY (fact_day, service_id, operator_id, event_type, status)
);
CREATE TABLE dw_fact_traffic (
  fact_day DATE NOT NULL,
  service_id BIGINT NOT NULL,
  operator_id BIGINT NOT NULL,
  channel VARCHAR(12) NOT NULL,
  kind VARCHAR(2) NOT NULL,
  state VARCHAR(30) NOT NULL,
  n BIGINT NOT NULL,
  PRIMARY KEY (fact_day, service_id, operator_id, channel, kind, state)
);
CREATE TABLE dw_fact_subscription (
  fact_day DATE NOT NULL,
  service_id BIGINT NOT NULL,
  activations BIGINT NOT NULL,
  stops BIGINT NOT NULL,
  PRIMARY KEY (fact_day, service_id)
);
CREATE TABLE dw_etl_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  finished_at TIMESTAMP WITH TIME ZONE,
  from_day DATE NOT NULL,
  to_day DATE NOT NULL,
  rows_loaded BIGINT NOT NULL DEFAULT 0,
  status VARCHAR(10) NOT NULL,
  error VARCHAR(500)
);
