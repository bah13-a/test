-- Scoring antifraude : dernier score de risque calculé par numéro actif, avec les variables qui l'expliquent.
CREATE TABLE fraud_score (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  msisdn VARCHAR(100) NOT NULL UNIQUE,
  score INT NOT NULL,
  features VARCHAR(1000) NOT NULL,
  decision VARCHAR(10) NOT NULL,
  computed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_fraud_score_score ON fraud_score (score, computed_at);
CREATE INDEX ix_ledger_msisdn_created ON ledger_event (msisdn, created_at);
