-- Modèles WhatsApp (approuvés par Meta) pour les envois à l'initiative du partenaire, hors fenêtre de 24 h.
CREATE TABLE chat_template (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_id BIGINT NOT NULL REFERENCES vas_service(id),
  name VARCHAR(512) NOT NULL,
  lang VARCHAR(10) NOT NULL,
  category VARCHAR(20) NOT NULL,
  body VARCHAR(1024) NOT NULL,
  param_count INT NOT NULL,
  approved BOOLEAN NOT NULL DEFAULT FALSE,
  approved_by VARCHAR(80),
  created_by VARCHAR(80) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_chat_template UNIQUE (service_id, name, lang)
);
